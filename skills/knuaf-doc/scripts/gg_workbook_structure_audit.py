#!/usr/bin/env python3
"""A derived form's *structure* audit, generated — never written by hand.

``gg_workbook_audit.build_result`` proves defects by re-running synthetic
probes.  Those probes need an input cell that holds a number, and the only
such workbooks are the professor's originals, which are not in this tree
(the blank bundled forms hold ``#DIV/0!``, text and empty cells at 10 of the
17 probe inputs).  So a derived form (today: ``school_17_sheet_v2``) gets a
structure audit instead: the formula inventory, the coverage counters, the
sheet roles and the source hash — no findings, hence no probes and no
example values.

That is all the registration contract reads.  ``registered_audit`` binds a
``schema`` and a ``source_sha256``; ``derivation_mismatches`` compares the
``inventory`` formulas only.  A structure audit therefore both admits the
form and its defined-transform copies and refuses a copy carrying another
form's audit.

Usage:
    gg_workbook_structure_audit.py --ref school_17_sheet_v2 \
        --source assets/templates/finance-template-v2.xlsx --out audit.json
    gg_workbook_structure_audit.py --ref ... --source ... --check audit.json
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

SCHEMA = "knuaf-workbook-formula-audit/v1"
SCOPE = "structure_only"
REFERENCES = Path(__file__).resolve().parents[1] / "references" / "common-workbooks"
ROLES_FILE = REFERENCES / "shared-finance-workbook.json"
# The 17-sheet form is one lineage; v2 differs in rows and formulas only, and
# its sheet names are the X01 names (measured), so the roles come from X01.
ROLE_MEMBER = "X01"


def sheet_roles(path: Path | None = None) -> dict:
    """``{sheet name: role}`` from the pinned shared-workbook extract."""
    data = json.loads(Path(path or ROLES_FILE).read_text(encoding="utf-8"))
    return {row["name"]: row["role"]
            for row in data["members"][ROLE_MEMBER]["sheet_meta"]}


def build(ref: str, source: Path, roles: dict) -> dict:
    import gg_workbook_audit as audit

    source = Path(source)
    book = audit.Workbook.load(source)
    entries, coverage = audit.inventory(book)
    missing = [name for name in book.sheets if name not in roles]
    if missing:
        raise ValueError("sheet roles missing for: " + ", ".join(missing))
    return {"schema": SCHEMA,
            "scope": SCOPE,
            "ref": ref,
            "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "sheet_roles": {name: roles[name] for name in book.sheets},
            "inventory": entries,
            "coverage": coverage,
            "model_farm_sheet": {"role": "example_only",
                                 "metadata_only": True}}


def json_bytes(doc: dict) -> bytes:
    return (json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True)
            + "\n").encode("utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", required=True,
                        help="binding key in references/common-workbooks/x01-crop-labels.json")
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--out", type=Path,
                        help="write here; without it the bytes go to stdout")
    parser.add_argument("--check", type=Path, metavar="AUDIT",
                        help="compare the generated bytes with an existing audit")
    parser.add_argument("--roles", type=Path,
                        help="sheet-role extract (default: shared-finance-workbook.json)")
    args = parser.parse_args(argv)

    payload = json_bytes(build(args.ref, args.source, sheet_roles(args.roles)))
    if args.check:
        existing = Path(args.check).read_bytes()
        if existing != payload:
            sys.stderr.write(f"structure audit differs from the generator: {args.check}\n")
            return 1
        sys.stdout.write(f"{args.check}: matches the generator\n")
        return 0
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_bytes(payload)
        sys.stdout.write(f"{args.out}: {len(payload)} bytes "
                         f"sha256 {hashlib.sha256(payload).hexdigest()}\n")
        return 0
    sys.stdout.buffer.write(payload)
    return 0


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):
        getattr(_stream, "reconfigure", lambda **_: None)(encoding="utf-8")
    raise SystemExit(main())
